#!/bin/sh
# Rebuilds walk_miner.ptx from walk_miner.cu with clang (no CUDA toolkit
# needed), and fails if a kernel would spill to local memory. Run it after
# changing walk_miner.cu or anything it includes from
# docs/walk-reference/cuda.
#
#   gen_ptx.sh          rebuild walk_miner.ptx
#   gen_ptx.sh --check  CI: compile afresh, and check walk_miner.ptx was built
#                       from the sources as they are now (its first line is
#                       their SHA-256, so the check holds across clang builds)
#
# sm_52 PTX runs on every NVIDIA GPU from Maxwell on: the driver compiles it
# for the card it finds, with that card's instructions.
set -eu
cd "$(dirname "$0")"
REF=../../../docs/walk-reference/cuda
CLANG=$(command -v clang++-18 || command -v clang++)
sources=$(cat walk_miner.cu "$REF/walk_core.h" "$REF/blake3_small.h" | sha256sum | cut -d' ' -f1)
out=$(mktemp)
trap 'rm -f "$out"' EXIT
"$CLANG" -x cuda --cuda-device-only --cuda-gpu-arch=sm_52 -nocudainc -nocudalib \
  -O3 -std=c++14 -Wall -Wextra -S walk_miner.cu -o "$out"
kernels=$(grep -c '^\.visible \.entry' "$out")
local_lines=$(grep -cE '\.local|__local_depot' "$out" || true)
echo "walk_miner: $kernels kernels, $local_lines lines of local memory"
[ "$kernels" -eq 5 ] || { echo "expected 5 kernels"; exit 1; }
[ "$local_lines" -eq 0 ] || { echo "a kernel uses local memory"; exit 1; }
if [ "${1:-}" = "--check" ]; then
  head -n 1 walk_miner.ptx | grep -qx "// sources sha256 $sources" || {
    echo "walk_miner.ptx was not built from these sources: run src/core/cuda/gen_ptx.sh"
    exit 1
  }
  echo "walk_miner.ptx matches its sources"
  exit 0
fi
{
  echo "// sources sha256 $sources"
  echo "// Generated by src/core/cuda/gen_ptx.sh from walk_miner.cu. Do not edit."
  grep -v '^// Generated by\|clang version' "$out"
} > walk_miner.ptx
